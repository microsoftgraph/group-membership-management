test('refresh metadata stays beside Refresh when the header wraps', async ({ page }) => {
  const refreshGroup = page.getByRole('group', { name: 'Refresh', exact: true });
  for (const width of [1280, 820, 480]) {
    await page.setViewportSize({ width, height: 1000 });
    const group = await refreshGroup.boundingBox();
    const timestamp = await refreshGroup.getByText(/^Last refreshed:/).boundingBox();
    const refresh = await refreshGroup.getByRole('button', { name: 'Refresh', exact: true }).boundingBox();
    if (!group || !timestamp || !refresh) {
      throw new Error('The snapshot timestamp and Refresh button must remain visible.');
    }
    expect(group.x).toBeGreaterThanOrEqual(0);
    expect(group.x + group.width).toBeLessThanOrEqual(width);
    expect(timestamp.x + timestamp.width).toBeLessThanOrEqual(refresh.x + 1);
    expect(timestamp.y + timestamp.height / 2).toBeCloseTo(refresh.y + refresh.height / 2, 0);

    const outputDirectory = process.env.HEALTH_DASHBOARD_SCREENSHOT_DIR;
    if (outputDirectory) {
      await refreshGroup.locator('..').screenshot({
        path: path.join(outputDirectory, `health-dashboard-toolbar-${width}.png`),
        animations: 'disabled',
      });
    }
  }
});
