test('activity ranges affect charts only and Refresh respects individual ranges', async ({ page }) => {
  const snapshot = page.getByRole('group', { name: 'Current snapshot', exact: true });
  const originalCounts = await snapshot.innerText();
  const timestamp = page.getByRole('group', { name: 'Refresh', exact: true }).getByText(/^Last refreshed:/);
  const originalTimestamp = await timestamp.innerText();
  const activityRange = page.getByRole('combobox', { name: 'Activity time range (charts only)', exact: true });
  const approvalsRange = page.getByRole('combobox', { name: 'Approvals & Rejections: Time range', exact: true });
  const onBehalfRange = page.getByRole('combobox', { name: 'Requests On Behalf Of: Time range', exact: true });
  const requests: string[] = [];
  page.on('request', (request) => {
    const url = new URL(request.url());
    if (url.pathname.includes('/api/v1/dashboard/')) {
      requests.push(url.pathname + url.search);
    }
  });

  for (const range of [
    { days: 14, option: '14 days', selected: 'Last 14 days' },
    { days: 30, option: '1 month', selected: 'Last 1 month' },
    { days: 90, option: '3 months', selected: 'Last 3 months' },
    { days: 7, option: '7 days', selected: 'Last 7 days' },
  ]) {
    requests.length = 0;
    await activityRange.locator('[data-icon-name="Calendar"]').click();
    await page.getByRole('option', { name: range.option, exact: true }).click();
    await expect(activityRange).toContainText(range.selected);
    await expect(approvalsRange).toContainText(range.selected);
    await expect(onBehalfRange).toContainText(range.selected);
    await expect(page.getByRole('button', { name: 'Refresh', exact: true })).toBeEnabled();
    expect(requests.slice().sort()).toEqual([
      `/api/v1/dashboard/approvals?windowDays=${range.days}`,
      `/api/v1/dashboard/onbehalf?windowDays=${range.days}`,
    ]);
    await expect(snapshot).toHaveText(originalCounts, { useInnerText: true });
    await expect(timestamp).toHaveText(originalTimestamp);
  }

  await approvalsRange.locator('[data-icon-name="Calendar"]').click();
  await page.getByRole('option', { name: '14 days', exact: true }).click();
  await expect(activityRange).toContainText('Individual ranges');
  await expect(onBehalfRange).toContainText('Last 7 days');
  await expect(page.getByRole('button', { name: 'Refresh', exact: true })).toBeEnabled();

  await onBehalfRange.locator('[data-icon-name="Calendar"]').click();
  await page.getByRole('option', { name: '3 months', exact: true }).click();
  await expect(activityRange).toContainText('Individual ranges');
  await expect(approvalsRange).toContainText('Last 14 days');
  await expect(onBehalfRange).toContainText('Last 3 months');
  await expect(page.getByRole('button', { name: 'Refresh', exact: true })).toBeEnabled();
  requests.length = 0;

  await page.getByRole('button', { name: 'Refresh', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Refresh', exact: true })).toBeEnabled();
  expect(requests.slice().sort()).toEqual([
    '/api/v1/dashboard/approvals?windowDays=14',
    '/api/v1/dashboard/onbehalf?windowDays=90',
    '/api/v1/dashboard/summary',
  ]);
});

for (const { title, endpoint, error, empty } of [
  {
    title: 'Approvals & Rejections',
    endpoint: 'approvals',
    error: 'Unable to load approval activity.',
    empty: 'No approvals or rejections in this window.',
  },
  {
    title: 'Requests On Behalf Of',
    endpoint: 'onbehalf',
    error: 'Failed to load the on behalf of activity.',
    empty: 'No on behalf of requests in this window.',
  },
]) {
  test(`${title} hides mismatched data after a failed range change but preserves matching refresh data`, async ({
    page,
  }) => {
    const section = page.getByRole('region', { name: title, exact: true });
    const selector = section.getByRole('combobox', { name: `${title}: Time range`, exact: true });
    const cards = section.getByRole('listitem');
    const chart = section.getByRole('img', { name: title, exact: true });
    const breakdown = section.getByText('Reviewer breakdown', { exact: true });
    const refresh = page.getByRole('button', { name: 'Refresh', exact: true });
    const snapshot = page.getByRole('group', { name: 'Current snapshot', exact: true });
    const originalSnapshot = await snapshot.innerText();
    const originalCounts = await cards.allTextContents();
    await breakdown.click();
    await expect(section.getByRole('grid')).toBeVisible();
    await expect(chart.first()).toBeVisible();

    const failure = {
      status: 500,
      contentType: 'application/json',
      body: JSON.stringify({ statusCode: 500, errorCode: 'DashboardUnavailable', activity: null }),
    };
    let releaseFailure: (() => void) | undefined;
    const pendingFailure = new Promise<void>((resolve) => {
      releaseFailure = resolve;
    });
    const routePattern = `**/api/v1/dashboard/${endpoint}?windowDays=30`;
    await page.route(
      routePattern,
      async (route) => {
        await pendingFailure;
        await route.fulfill(failure);
      },
      { times: 1 }
    );

    try {
      await selector.click();
      await page.getByRole('option', { name: '1 month', exact: true }).click();
      await expect(selector).toContainText('Last 1 month');
      await expect(section).toHaveAttribute('aria-busy', 'true');
      await expect(section.getByText('Loading activity...', { exact: true })).toBeVisible();
      await expect(cards).toHaveCount(0);
      await expect(chart).toHaveCount(0);
      await expect(breakdown).toHaveCount(0);
    } finally {
      releaseFailure?.();
    }

    await expect(section.getByText(error, { exact: true })).toBeVisible();
    await expect(section).toHaveAttribute('aria-busy', 'false');
    await expect(selector).toContainText('Last 1 month');
    await expect(cards).toHaveCount(0);
    await expect(chart).toHaveCount(0);
    await expect(breakdown).toHaveCount(0);
    await expect(section.getByText(empty, { exact: true })).toHaveCount(0);
    await expect(snapshot).toHaveText(originalSnapshot, { useInnerText: true });

    await refresh.click();
    await expect(refresh).toBeEnabled();
    await expect(section.getByText(error, { exact: true })).toHaveCount(0);
    await expect(selector).toContainText('Last 1 month');
    await expect(chart.first()).toBeVisible();
    const monthCounts = await cards.allTextContents();
    expect(monthCounts).not.toEqual(originalCounts);
    await breakdown.click();
    const monthReviewers = await section.getByRole('grid').innerText();

    await page.route(routePattern, (route) => route.fulfill(failure), { times: 1 });
    await refresh.click();
    await expect(section.getByText(error, { exact: true })).toBeVisible();
    await expect(refresh).toBeEnabled();
    await expect(selector).toContainText('Last 1 month');
    expect(await cards.allTextContents()).toEqual(monthCounts);
    await expect(chart.first()).toBeVisible();
    await expect(section.getByRole('grid')).toHaveText(monthReviewers, { useInnerText: true });
    await expect(section.getByText(empty, { exact: true })).toHaveCount(0);
  });
}

