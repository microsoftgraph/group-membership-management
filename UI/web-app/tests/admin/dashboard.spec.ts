test('anomalous table distributes its columns across the card as the viewport changes', async ({ page }) => {
  const section = page.getByRole('region', { name: 'Anomalous Statuses', exact: true });
  const grid = section.getByRole('grid');
  const headers = grid.getByRole('columnheader');
  await expect(headers).toHaveText(['Status', 'Count', 'Max Cycles Missed', 'Oldest Last Success', 'Never Succeeded']);

  for (const width of [1920, 1280, 1920]) {
    await page.setViewportSize({ width, height: 1000 });
    await expect
      .poll(
        () =>
          headers.last().evaluate((header) => {
            const table = header.closest('[role="grid"]');
            if (!table) {
              throw new Error('The anomalous status header must belong to its grid.');
            }
            const headerBox = header.getBoundingClientRect();
            const tableBox = table.getBoundingClientRect();
            return {
              usesRightSide: headerBox.x - tableBox.x > tableBox.width * 0.7,
              balancedWidth: headerBox.width < tableBox.width * 0.3,
              fillsWidth: Math.abs(headerBox.right - tableBox.right) <= 1,
            };
          }),
        { message: `The columns must use the full table width at ${width}px.` }
      )
      .toEqual({ usesRightSide: true, balancedWidth: true, fillsWidth: true });
    await expect(grid.getByRole('row')).toHaveCount(3);
    await expect(grid.getByRole('row').nth(1)).toContainText('SchemaError');
    await expect(grid.getByRole('row').nth(2)).toContainText('Error');
  }

  const outputDirectory = process.env.HEALTH_DASHBOARD_SCREENSHOT_DIR;
  if (outputDirectory) {
    await mkdir(outputDirectory, { recursive: true });
    await section.screenshot({
      path: path.join(outputDirectory, 'health-dashboard-anomalous-table-wide.png'),
      animations: 'disabled',
    });
  }
});

test('anomalous table keeps all columns in a local scroller on narrow screens', async ({ page }) => {
  const section = page.getByRole('region', { name: 'Anomalous Statuses', exact: true });
  const grid = section.getByRole('grid');

  for (const width of [820, 480]) {
    await page.setViewportSize({ width, height: 1000 });
    await grid.scrollIntoViewIfNeeded();
    await expect(grid.getByRole('columnheader')).toHaveCount(5);
    await expect(grid.getByRole('row')).toHaveCount(3);

    const layout = await grid.evaluate((table) => {
      let scroller = table.parentElement;
      while (scroller && getComputedStyle(scroller).overflowX !== 'auto') {
        scroller = scroller.parentElement;
      }
      if (!scroller) {
        throw new Error('The anomalous table must have its own horizontal scroller.');
      }
      scroller.scrollLeft = scroller.scrollWidth;
      const { x, width } = scroller.getBoundingClientRect();
      return { x, width, clientWidth: scroller.clientWidth, scrollWidth: scroller.scrollWidth };
    });
    expect(layout.x).toBeGreaterThanOrEqual(0);
    expect(layout.x + layout.width).toBeLessThanOrEqual(width);
    expect(layout.scrollWidth).toBeGreaterThanOrEqual(layout.clientWidth);
    await expect(grid.getByRole('columnheader', { name: 'Never Succeeded', exact: true })).toBeInViewport();
  }
});

